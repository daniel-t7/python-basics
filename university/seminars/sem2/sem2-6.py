"""
Да се напише програма, която създава списък с имена на градове
и извършва действия с него. Действията включват: добавяне и изтриване на
елемент, извеждане на списъка, сортиране на списъка, търсене на елемент в
списъка и конкатезиране на списъци. При избор на тази опция се създава нов
списък с елементи, въведени от потребителя. След това новия списък се
конкатенира със съществуващия списък.
"""

cities = []

# Добавяне
n = int(input("Колко града да въведеш: "))

for i in range(n):
    city = input("Въведи град: ")
    cities.append(city)

# Извеждане
print("Градове:", cities)

# Добавяне на нов град
city = input("Град за добавяне: ")
cities.append(city)

print("След добавяне:", cities)

# Изтриване
city = input("Град за изтриване: ")

if city in cities:
    cities.remove(city)

print("След изтриване:", cities)

# Сортиране
cities.sort()

print("Сортирани градове:", cities)

# Търсене
city = input("Град за търсене: ")

if city in cities:
    print("Градът е намерен.")
else:
    print("Градът не е намерен.")

# Нов списък
new_cities = []

n = int(input("Колко града да добавиш в новия списък: "))

for i in range(n):
    city = input("Въведи град: ")
    new_cities.append(city)

# Конкатенация
cities = cities + new_cities

print("След конкатенация:", cities)